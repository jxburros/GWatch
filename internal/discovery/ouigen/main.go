// Command ouigen builds the compact vendor list discovery embeds
// (internal/discovery/oui.txt.gz) from the IEEE's public registry of
// organisationally unique identifiers — the first three bytes of a MAC
// address, assigned to the company that made the network card.
//
// Run it from internal/discovery with `go generate`, which downloads the
// registry; or point it at a copy already on disk:
//
//	go run ./ouigen -in oui.csv -out oui.txt.gz
//
// Only the large (MA-L, 24-bit) blocks are kept. The medium and small
// blocks (MA-M, MA-S) are sub-assignments of a few thousand addresses each,
// mostly to industrial makers nobody has on a home network, and resolving
// them would mean matching 28 and 36 bits instead of a simple three-byte
// lookup. The names are shortened — "Synology Incorporated" and "Seiko Epson
// Corporation" read better in a narrow column as "Synology" and "Seiko Epson"
// — and the output is sorted and gzipped with no timestamp, so the same
// registry always produces the same bytes and a regenerated file only shows
// in a diff when the registry itself changed.
package main

import (
	"bufio"
	"compress/gzip"
	"encoding/csv"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"regexp"
	"sort"
	"strings"
	"time"
)

const registryURL = "https://standards-oui.ieee.org/oui/oui.csv"

func main() {
	in := flag.String("in", "", "a downloaded oui.csv; empty downloads "+registryURL)
	out := flag.String("out", "oui.txt.gz", "the file to write")
	flag.Parse()

	var src io.Reader
	if *in == "" {
		client := &http.Client{Timeout: 2 * time.Minute}
		resp, err := client.Get(registryURL)
		if err != nil {
			fail(err)
		}
		defer resp.Body.Close()
		if resp.StatusCode != http.StatusOK {
			fail(fmt.Errorf("%s answered HTTP %d", registryURL, resp.StatusCode))
		}
		src = resp.Body
	} else {
		f, err := os.Open(*in)
		if err != nil {
			fail(err)
		}
		defer f.Close()
		src = f
	}

	entries, err := parse(src)
	if err != nil {
		fail(err)
	}
	if len(entries) < 10000 {
		fail(fmt.Errorf("only %d assignments read; that is not the IEEE registry", len(entries)))
	}
	if err := write(*out, entries); err != nil {
		fail(err)
	}
	fmt.Printf("wrote %d vendors to %s\n", len(entries), *out)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "ouigen:", err)
	os.Exit(1)
}

// parse reads the registry's CSV: Registry, Assignment, Organization Name,
// Organization Address.
func parse(r io.Reader) (map[string]string, error) {
	cr := csv.NewReader(bufio.NewReader(r))
	cr.FieldsPerRecord = -1
	cr.LazyQuotes = true
	out := map[string]string{}
	for {
		rec, err := cr.Read()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, err
		}
		if len(rec) < 3 || rec[0] != "MA-L" {
			continue
		}
		prefix := strings.ToUpper(strings.TrimSpace(rec[1]))
		if len(prefix) != 6 {
			continue
		}
		name := shorten(rec[2])
		if name == "" || strings.EqualFold(name, "Private") {
			continue
		}
		out[prefix] = name
	}
	return out, nil
}

// corporateSuffix matches the legal-form endings that make a vendor column
// three times as wide as it needs to be, repeatedly: "Co., Ltd." is two.
var corporateSuffix = regexp.MustCompile(`(?i)[\s,.]+(inc|incorporated|corp|corporation|co|company|ltd|limited|llc|l\.l\.c|gmbh|ag|sa|s\.a|srl|s\.r\.l|spa|s\.p\.a|bv|b\.v|nv|n\.v|ab|as|a/s|oy|oyj|kg|kk|pty|plc|pte|sas|sarl|technology|technologies|tech)\.?$`)

// shorten trims a registered company name to what a person would call it.
func shorten(name string) string {
	name = strings.Join(strings.Fields(name), " ")
	for {
		trimmed := strings.TrimRight(corporateSuffix.ReplaceAllString(name, ""), " ,.")
		if trimmed == name || trimmed == "" {
			break
		}
		name = trimmed
	}
	if len(name) > 40 {
		name = strings.TrimSpace(name[:40])
	}
	return name
}

func write(path string, entries map[string]string) error {
	keys := make([]string, 0, len(entries))
	for k := range entries {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	f, err := os.Create(path)
	if err != nil {
		return err
	}
	zw, err := gzip.NewWriterLevel(f, gzip.BestCompression)
	if err != nil {
		f.Close()
		return err
	}
	w := bufio.NewWriter(zw)
	fmt.Fprintf(w, "# IEEE MA-L registry (%s), %d assignments, generated by internal/discovery/ouigen\n", registryURL, len(keys))
	for _, k := range keys {
		fmt.Fprintf(w, "%s\t%s\n", k, entries[k])
	}
	if err := w.Flush(); err != nil {
		f.Close()
		return err
	}
	if err := zw.Close(); err != nil {
		f.Close()
		return err
	}
	return f.Close()
}
